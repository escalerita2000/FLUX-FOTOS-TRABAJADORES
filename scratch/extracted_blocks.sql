-- Name: get_current_bogota_date(); Type: FUNCTION; Schema: public; Owner: postgres
--

CREATE FUNCTION public.get_current_bogota_date() RETURNS date
    LANGUAGE plpgsql
    AS $$
BEGIN
  RETURN (CURRENT_TIMESTAMP AT TIME ZONE 'America/Bogota')::DATE;
END;
$$;


ALTER FUNCTION public.get_current_bogota_date() OWNER TO postgres;

